def P(text, size=10.5, bold=False, color=None, italic=False, after=6):
    par = doc.add_paragraph()
    par.paragraph_format.space_after = Pt(after)
    r = par.add_run(text)
    set_run_font(r, FONT_BODY, size, bold=bold, color=color, italic=italic)
    return par


def LEAD(text):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.cell(0, 0)
    cell.width = Cm(16.2)
    shade(cell, "F4F1EC")
    tcpr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge, sz, col in (("left", 24, "B44A1E"), ("top", 2, "F4F1EC"),
                          ("bottom", 2, "F4F1EC"), ("right", 2, "F4F1EC")):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), str(sz))
        el.set(qn("w:color"), col)
        borders.append(el)
    tcpr.append(borders)
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(6)
    p.paragraph_format.line_spacing = 1.35
    r = p.add_run(text)
    set_run_font(r, FONT_BODY, 10.5, color=RGBColor(0x33, 0x2A, 0x22))
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def BULLET(text, size=10.5, level=0):
    par = doc.add_paragraph(style="List Bullet")
    par.paragraph_format.space_after = Pt(3)
    par.paragraph_format.left_indent = Cm(0.75 + level * 0.6)
    par.paragraph_format.line_spacing = 1.4
    r = par.add_run(text)
    set_run_font(r, FONT_BODY, size)
    return par


def TBL(headers, rows, widths=None, header_bg="0F243E", font_size=9):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_borders(t)
    cell_margins(t)
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        shade(hdr[i], header_bg)
        p = hdr[i].paragraphs[0]
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.2
        r = p.add_run(h)
        set_run_font(r, FONT_HEAD, font_size, bold=True, color=WHITE)
        if widths:
            hdr[i].width = Cm(widths[i])
    for ridx, row in enumerate(rows):
        cells = t.add_row().cells
        for i, val in enumerate(row):
            if widths:
                cells[i].width = Cm(widths[i])
            if ridx % 2 == 1:
                shade(cells[i], "F7F8F9")
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.line_spacing = 1.25
            r = p.add_run(str(val))
            set_run_font(r, FONT_BODY, font_size)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def CALLOUT(title, text, bg="EAF0F6", bar="0F243E"):
    tbl = doc.add_table(rows=1, cols=1)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = tbl.cell(0, 0)
    cell.width = Cm(16.2)
    shade(cell, bg)
    tcpr = cell._tc.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for edge, sz, col in (("left", 20, bar), ("top", 2, bg), ("bottom", 2, bg), ("right", 2, bg)):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), str(sz))
        el.set(qn("w:color"), col)
        borders.append(el)
    tcpr.append(borders)
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(5)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.3
    r = p.add_run(title)
    set_run_font(r, FONT_HEAD, 10, bold=True, color=NAVY)
    p2 = cell.add_paragraph()
    p2.paragraph_format.space_after = Pt(5)
    p2.paragraph_format.line_spacing = 1.4
    r2 = p2.add_run(text)
    set_run_font(r2, FONT_BODY, 10)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


